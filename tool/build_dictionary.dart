import 'dart:convert';
import 'dart:io';

import '../lib/data/normalization.dart';

Future<void> main(List<String> args) async {
  final input = File(args.isEmpty ? './data.json' : args.first);
  final rows = (jsonDecode(await input.readAsString()) as List)
      .cast<Map<String, dynamic>>();
  final ids = <int, int>{};
  final exact = <String, List<int>>{};
  final loose = <String, Set<String>>{};
  final emptyWordIds = <Object?>[];
  final emptyMeaningIds = <Object?>[];
  var emptyWords = 0, emptyMeanings = 0, letterMismatch = 0;
  for (final e in rows) {
    final word = e['word']?.toString() ?? '',
        urdu = e['urdu_meaning']?.toString() ?? '',
        en = e['english_translation']?.toString() ?? '';
    final forms = word
        .split(RegExp(r'[/،]'))
        .map((s) => s.trim())
        .where((s) => s.isNotEmpty)
        .toSet()
        .toList();
    void keep(String key, Object defaultValue) {
      final v = e[key];
      if (v == null || (v is String && v.isEmpty) || (v is List && v.isEmpty))
        e[key] = defaultValue;
    }

    keep('variants', forms);
    keep('pos', '');
    keep('roman', '');
    keep('ipa', '');
    keep('audio', '');
    keep('sentences', []);
    keep('tags', []);
    keep('source', '');
    if (!e.containsKey('page')) e['page'] = null;
    if (!e.containsKey('parent_id')) e['parent_id'] = null;
    final variants = (e['variants'] as List).map((v) => v.toString()).toList();
    final wn = DictionaryNormalization.normalize(word),
        wl = DictionaryNormalization.normalize(word, loose: true);
    e['word_norm'] = wn;
    e['word_loose'] = wl;
    e['variants_norm'] = variants
        .map(DictionaryNormalization.normalize)
        .toList();
    e['variants_loose'] = variants
        .map((v) => DictionaryNormalization.normalize(v, loose: true))
        .toList();
    e['urdu_norm'] = DictionaryNormalization.normalize(urdu);
    e['english_norm'] = DictionaryNormalization.normalize(en);
    e['urdu_glosses_norm'] = DictionaryNormalization.glosses(urdu);
    e['english_glosses_norm'] = DictionaryNormalization.glosses(
      en,
      english: true,
    );
    e['english_gloss_stems'] = (e['english_glosses_norm'] as List)
        .map((gloss) => DictionaryNormalization.englishStems('$gloss'))
        .toList();
    e['urdu_gloss_tokens'] = (e['urdu_glosses_norm'] as List)
        .map(
          (gloss) =>
              '$gloss'.split(' ').where((token) => token.isNotEmpty).toList(),
        )
        .toList();
    if (word.trim().isEmpty) {
      emptyWords++;
      emptyWordIds.add(e['id']);
    }
    if (urdu.trim().isEmpty && en.trim().isEmpty) {
      emptyMeanings++;
      emptyMeaningIds.add(e['id']);
    }
    final id = e['id'];
    if (id is int) ids.update(id, (n) => n + 1, ifAbsent: () => 1);
    final signature = '$word\u0000$urdu\u0000$en';
    (exact[signature] ??= <int>[]).add(id is int ? id : -1);
    (loose[wl] ??= <String>{}).add(wn);
    final letter = e['letter']?.toString() ?? '';
    if (word.isNotEmpty &&
        letter.isNotEmpty &&
        word.runes.first != letter.runes.first)
      letterMismatch++;
  }
  final serialized = '${const JsonEncoder.withIndent('  ').convert(rows)}\n';
  final out = File('assets/data/dictionary.built.json')
    ..createSync(recursive: true);
  await out.writeAsString(serialized);
  final versionFile = File('lib/config/dictionary_data_version.dart');
  await versionFile.writeAsString(
    '''// Generated by tool/build_dictionary.dart. Do not edit by hand.
class DictionaryDataVersion {
  static const entryCount = ${rows.length};
  static const contentHash = '${_fnv1a(serialized)}';
  static const value = '\$entryCount-\$contentHash';
}
''',
  );
  final worker = File('web/service-worker.js');
  if (await worker.exists()) {
    final source = await worker.readAsString();
    await worker.writeAsString(
      source.replaceFirst(
        RegExp(r"const CACHE = 'brahui-dictionary-shell-[^']+';"),
        "const CACHE = 'brahui-dictionary-shell-${rows.length}-${_fnv1a(serialized)}';",
      ),
    );
  }
  final dupIds = ids.entries.where((e) => e.value > 1).toList();
  final dupWords = exact.entries.where((e) => e.value.length > 1).toList();
  final collisions = loose.entries.where((e) => e.value.length > 1).toList();
  final report = StringBuffer(
    'Dictionary validation report\nEntries: ${rows.length}\nEmpty word count: $emptyWords (ids: ${emptyWordIds.join(', ')})\nBoth meanings empty count: $emptyMeanings (ids: ${emptyMeaningIds.join(', ')})\nDuplicate id values: ${dupIds.map((e) => e.key).join(', ')}\nExact duplicate groups: ${dupWords.length}\n',
  );
  for (final duplicate in dupWords) {
    report.writeln(
      '  duplicate ids ${duplicate.value.join(', ')}: ${duplicate.key.replaceAll('\u0000', ' | ')}',
    );
  }
  report.writeln('Loose-normalization collisions: ${collisions.length}');
  for (final c in collisions) {
    report.writeln('  ${c.key}: ${c.value.join(' | ')}');
  }
  report.writeln(
    'First-letter mismatch count (word vs letter field): $letterMismatch',
  );
  final reportFile = File('build/data_report.txt')..createSync(recursive: true);
  await reportFile.writeAsString(report.toString());
  stdout.write(
    'Built ${rows.length} entries → ${out.path}\n${report.toString()}',
  );
}

String _fnv1a(String input) {
  var hash = 0x811c9dc5;
  for (final unit in input.codeUnits) {
    hash = ((hash ^ unit) * 0x01000193) & 0xffffffff;
  }
  return hash.toRadixString(16).padLeft(8, '0');
}
